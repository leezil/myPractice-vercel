def load_existing_index() -> list[dict]:
    index_path = ROOT / "content" / "r2-seed" / "index.json"
    if not index_path.exists():
        return []
    return json.loads(index_path.read_text(encoding="utf-8"))


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    new_entries: list[dict] = []
    eco_slugs = {s["slug"] for s in SETS}

    for meta in SETS:
        data = {
            "slug": meta["slug"],
            "title": meta["title"],
            "subject": SUBJECT,
            "description": meta["description"],
            "questions": meta["questions"],
        }
        out_path = OUT_DIR / f"{meta['slug']}.json"
        out_path.write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        new_entries.append(
            {
                "slug": meta["slug"],
                "title": meta["title"],
                "subject": SUBJECT,
                "description": meta["description"],
                "questionCount": len(meta["questions"]),
            }
        )
        print(f"{meta['slug']}: {len(meta['questions'])} questions")

    existing = load_existing_index()
    merged = [e for e in existing if e["slug"] not in eco_slugs]
    merged.extend(new_entries)
    merged.sort(key=lambda x: x["slug"])

    index_path = ROOT / "content" / "r2-seed" / "index.json"
    index_path.write_text(
        json.dumps(merged, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    total = sum(e["questionCount"] for e in new_entries)
    print(f"eco total: {total} questions, index.json: {len(merged)} sets")


if __name__ == "__main__":
    main()
